/** Whether a file was written, or kept because it was there already. */
type Written = "wrote" | "kept";

/** Writes `files` (name to text) into `dir`, keeping the ones that exist unless `force`; `ownerOnly` creates the directory 0700. */
async function writeFiles(
	dir: string,
	files: ReadonlyMap<string, string>,
	options: { readonly force: boolean; readonly ownerOnly: boolean },
): Promise<[string, Written][]> {
	await (options.ownerOnly ? privateDir(dir) : mkdir(dir, { recursive: true }));
	return Promise.all(
		[...files].map(async ([name, text]): Promise<[string, Written]> => {
			const file = join(dir, name);
			try {
				await writeFile(file, text, { flag: options.force ? "w" : "wx" });
				return [file, "wrote"];
			} catch (error) {
				if (errnoOf(error) === "EEXIST") {
					return [file, "kept"];
				}
				throw error;
			}
		}),
	);
}

