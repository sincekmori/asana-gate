/** What `asana-gate init` writes: a policy skeleton, settings files and a .gitignore. */

/** How many teams and projects the policy skeleton lists. */
const MAX_LISTED = 50;

/** The comment that makes editors validate a file against its JSON Schema. */
const pointer = (url: string): string => `# yaml-language-server: $schema=${url}`;

const yamlString = (value: string): string => JSON.stringify(value);

/** The policy skeleton of a workspace: read-only everywhere, its teams and projects listed as commented examples. */
function renderPolicy(
	workspace: Named,
	teams: readonly Named[],
	projects: readonly Named[],
): string {
	const lines = [
		pointer(POLICY_SCHEMA_URL),
		"# asana-gate policy — generated by `asana-gate init`.",
		"# Nothing is allowed unless a rule allows it; the most specific rule wins and deny wins ties.",
		"# Actions are <resource>:<verb>; read / modify / write / admin are groups. See the README for the vocabulary.",
		"version: 1",
		`workspace: ${yamlString(workspace.gid)} # ${workspace.name}`,
		"",
		"rules:",
		"  # Start read-only everywhere.",
		"  - allow: [read]",
		"",
		"  # Example: full task work inside one project, but nothing changes in its Done section.",
		'  # - where: { project: "<project gid>" }',
		"  #   allow: [task:*, story:create, tag:apply]",
		'  # - where: { project: "<project gid>", section: "Done" }',
		"  #   deny: [modify]",
		"",
		"  # Example: limited updates (only these fields) on tasks assigned to the token owner.",
		"  # - where: { assignee: me }",
		"  #   allow: [read]",
		"  #   fields: { task: [completed, due_on] }",
		"",
	];
	if (teams.length > 0) {
		lines.push("  # Teams in this organization:");
		for (const team of teams) {
			lines.push(
				`  # - where: { team: ${yamlString(team.gid)} } # ${team.name}`,
				"  #   allow: [write]",
			);
		}
		lines.push("");
	}
	if (projects.length > 0) {
		lines.push(
			`  # Projects (${projects.length === MAX_LISTED ? `first ${MAX_LISTED}` : projects.length}):`,
		);
		for (const project of projects) {
			lines.push(
				`  # - where: { project: ${yamlString(project.gid)} } # ${project.name}`,
				"  #   allow: [task:*, story:create]",
			);
		}
		lines.push("");
	}
	return `${lines.join("\n")}\n`;
}

/** The defaults as commented YAML, so a settings file shows what it may override (the MCP defaults aside). */
function commentedDefaults(): string {
	const { token, log, cache, concurrency, retries } = DEFAULTS;
	return stringify({ token, log, cache, concurrency, retries })
		.trimEnd()
		.split("\n")
		.map((line) => `# ${line}`)
		.join("\n");
}

/** The settings file of a project, shared through the repository; it names the policy beside it. */
